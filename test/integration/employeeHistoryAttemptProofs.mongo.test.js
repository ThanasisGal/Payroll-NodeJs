"use strict";
const {test}=require('node:test');const assert=require('node:assert/strict');const mongoose=require('mongoose');
const {createHash}=require('node:crypto');const F=require('../fixtures/employeeHistoryApprovedProposalMongo');
const {createAttemptProofs}=require('../../server/services/ergazomenoi/employeeHistoryAttemptProofs');
const binary=process.env.PAYROLL_APPROVED_PROPOSAL_TEST_MONGOD;
test('Attempt proofs: exact SHA, conflicting duplicates, write conflicts, original BSON and no transaction reuse',{skip:!binary,timeout:60000},async t=>{
 const db=await F.startApprovedProposalMongo(binary);t.after(db.close);const f=await F.seedApprovedProposal(db);
 const id=new mongoose.Types.ObjectId(),collection=db.frozenModel.collection.name;
 await db.frozenModel.collection.insertOne({_id:id,...f.scope,period_start:new Date('2026-01-01'),period_end:new Date('2026-12-31'),frozen_snapshot:{private:[new mongoose.mongo.BSON.Int32(1),new mongoose.mongo.BSON.Double(2)]}});
 const raw=await db.frozenModel.collection.findOne({_id:id},{raw:true});
 const identityBson=mongoose.mongo.BSON.serialize({_id:id}).toString('base64'),sha256=createHash('sha256').update(raw).digest('hex');
 const session=await db.connection.startSession();t.after(()=>session.endSession());
 const begin=async()=>{session.startTransaction();await db.frozenModel.collection.findOne({_id:id},{session,projection:{_id:1}});return createAttemptProofs(db.connection,session);};
 let proofs=await begin();proofs.remember(collection,raw);
 await assert.rejects(proofs.claim([{collection,identityBson,sha256:'0'.repeat(64)}]),e=>e.reason==='STALE');await session.abortTransaction();
 proofs=await begin();proofs.remember(collection,raw);
 await proofs.claim([{collection,identityBson,sha256},{collection,identityBson,sha256}]);
 assert.deepEqual(await db.frozenModel.collection.findOne({_id:id},{session,raw:true}),raw);
 await session.abortTransaction();
 const old=proofs;proofs=await begin();await assert.rejects(old.load(collection,[identityBson]),e=>e.reason==='BOUNDARY');await session.abortTransaction();
 proofs=await begin();proofs.remember(collection,raw);
 await db.frozenModel.collection.updateOne({_id:id},{$set:{'frozen_snapshot.private':[9]}},{session});
 await assert.rejects(proofs.claim([{collection,identityBson,sha256}]),e=>e.reason==='STALE');await session.abortTransaction();
 assert.deepEqual(await db.frozenModel.collection.findOne({_id:id},{raw:true}),raw);
 proofs=await begin();proofs.remember(collection,raw);
 await db.frozenModel.collection.updateOne({_id:id},{$set:{'frozen_snapshot.private':[8]}});
 await assert.rejects(proofs.claim([{collection,identityBson,sha256}]),e=>e.code===112||e.hasErrorLabel?.('TransientTransactionError'));await session.abortTransaction();
 assert.equal(await db.auditModel.countDocuments({mutationSource:'EMPLOYEE_HISTORY_APPROVED_XLSX_APPLY'}),0);
});
